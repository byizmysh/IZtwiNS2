#!/usr/bin/env python3
"""Bind the bundled font faces to the native executable's read-only data."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent
output = Path(sys.argv[1])
files = [line.split() for line in (root / "fonts/list.txt").read_text().splitlines() if line.strip()]
assembly = [".section .rodata.iztwins_font_assets", ".balign 16"]
header = ["/* Generated by font-assets.py. */"]
rows = []
for index, (script, source) in enumerate(files):
    path = root / source
    if len(script) != 4 or not path.is_file():
        raise SystemExit(f"Invalid font entry: {script} {source}")
    symbol = f"font_blob_{index}"
    assembly.extend((f".global {symbol}", f".hidden {symbol}", f"{symbol}:",
                     f".incbin {json.dumps(str(path), ensure_ascii=False)}", ".balign 16"))
    header.append(f"extern const unsigned char {symbol}[];")
    script_tag = ", ".join(f"'{c}'" for c in script)
    rows.append(f"    {{{symbol}, {path.stat().st_size}, HB_TAG({script_tag})}},")
assembly.append('.section .note.GNU-stack,""')
header.extend(["static const FontAsset font_assets[] = {", *rows, "};"])
(output / "text-assets.S").write_text("\n".join(assembly) + "\n")
(output / "text-assets.h").write_text("\n".join(header) + "\n")
